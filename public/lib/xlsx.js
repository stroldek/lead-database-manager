// Minimal dependency-free XLSX writer (single sheet, text cells, uncompressed ZIP).
// Enough for the test export; the full export module (stage 7) can replace it behind the same function.
const enc = new TextEncoder();

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

export function crc32(bytes) {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function escapeXml(value) {
  return String(value ?? '')
    // XML 1.0 forbids most control chars; they appear in chat messages sometimes.
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\uFFFE\uFFFF]/g, '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function colName(index) {
  let n = index + 1;
  let s = '';
  while (n > 0) {
    const r = (n - 1) % 26;
    s = String.fromCharCode(65 + r) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

function sheetXml(headers, rows, widths) {
  const lastCol = colName(headers.length - 1);
  const cell = (c, r, text, style) =>
    `<c r="${colName(c)}${r}" t="inlineStr"${style ? ` s="${style}"` : ''}><is><t xml:space="preserve">${escapeXml(text)}</t></is></c>`;
  const parts = [];
  parts.push('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>');
  parts.push('<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">');
  parts.push(`<dimension ref="A1:${lastCol}${rows.length + 1}"/>`);
  parts.push('<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>');
  parts.push('<sheetFormatPr defaultRowHeight="15"/>');
  parts.push('<cols>' + headers.map((_, i) => `<col min="${i + 1}" max="${i + 1}" width="${widths[i] || 20}" customWidth="1"/>`).join('') + '</cols>');
  parts.push('<sheetData>');
  parts.push('<row r="1">' + headers.map((h, c) => cell(c, 1, h, 1)).join('') + '</row>');
  rows.forEach((row, i) => {
    const r = i + 2;
    parts.push(`<row r="${r}">` + row.map((v, c) => cell(c, r, v, 2)).join('') + '</row>');
  });
  parts.push('</sheetData>');
  parts.push(`<autoFilter ref="A1:${lastCol}${rows.length + 1}"/>`);
  parts.push('</worksheet>');
  return parts.join('');
}

